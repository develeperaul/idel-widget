const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');

const apartment = { id: 1, type: 'apartment', number: '17', area: 55, price: 12000000, status: 'available', floor: 4, section: { id: 154, name: 'Секция 2' }, apartment: { rooms: 2, planImage: null } };
const metadata = { options: { section: [], rooms: [], features: [] }, bounds: { floor: { min: 1, max: 19 }, area: { min: 30, max: 150 }, price: { min: 5000000, max: 30000000 } } };

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
    const errors = [], commands = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/**', route => {
      const url = new URL(route.request().url());
      if (url.pathname.endsWith('/filters')) return route.fulfill({ json: metadata });
      if (url.pathname.endsWith('/properties')) return route.fulfill({ json: { items: [apartment], meta: { hasNext: false, totalPages: 1 } } });
      if (url.pathname.endsWith('/properties/apartment/1')) return route.fulfill({ json: { item: apartment } });
      return route.fulfill({ json: { items: [] } });
    });
    await page.goto(pathToFileURL(path.join(__dirname, 'index.html')).href, { waitUntil: 'domcontentloaded', timeout: 90000 });
    await page.evaluate(() => { window.commands = []; window.addEventListener('idel-command', event => commands.push(event.detail)); });
    await page.locator('#start').click();
    await page.locator('#phone').fill('+7 (999) 123-45-67');
    await page.locator('#manager-toggle').click();
    await page.locator('[data-manager="0"]').click();
    await page.getByRole('button', { name: 'Войти', exact: true }).click();
    assert.equal(await page.evaluate(() => JSON.stringify(IdelSession.getState()).includes('999')), false);
    assert.equal(await page.evaluate(() => JSON.stringify(commands.find(item => item.method === 'session.started')).includes('999')), false);
    await page.locator('[data-action="ui.apartments"]').click();
    await page.getByText('Найдено: 1', { exact: true }).waitFor();
    await page.locator('[data-apartment-mode=list]').click();
    await page.locator('.apt-list-favorite').click();
    await page.locator('[data-action="scene.screenshot"]').click();
    const capture = await page.evaluate(() => commands.at(-1).params);
    const png = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
    assert.equal(await page.evaluate(({ capture, png }) => IdelApartments.setScreenshot({ ...capture, url: png }), { capture, png }), true);
    await page.locator('.screenshot-flight').waitFor({ state: 'visible' });
    await page.locator('[data-action="ui.favorites"]').click();
    await page.getByRole('region', { name: 'Сохранённое' }).waitFor();
    await page.setViewportSize({ width: 3840, height: 2160 });
    const savedBox = await page.getByRole('region', { name: 'Сохранённое' }).boundingBox();
    assert.ok(savedBox.x >= 1000 && savedBox.x + savedBox.width <= 3840);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.getByRole('button', { name: 'Отправить на почту' }).click();
    await page.getByRole('dialog', { name: 'Отправить на почту' }).locator('#share-keyboard').getByRole('button', { name: '@', exact: true }).click();
    assert.equal(await page.getByRole('dialog', { name: 'Отправить на почту' }).getByRole('textbox', { name: 'Электронная почта' }).inputValue(), '@');
    await page.getByRole('dialog', { name: 'Отправить на почту' }).getByRole('button', { name: 'Отправить через Telegram' }).click();
    assert.ok((await page.getByRole('dialog', { name: 'Отправить через telegram' }).innerText()).includes('бот не подключён'));
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Выйти из сессии' }).click();
    await page.getByRole('dialog', { name: 'Выйти из сессии' }).getByRole('button', { name: 'Сохранить избранное и выйти' }).click();
    await page.locator('#welcome').waitFor({ state: 'visible' });
    assert.equal(await page.evaluate(() => commands.find(item => item.method === 'session.ended')?.params.savedLocally), true);
    assert.equal(await page.evaluate(() => IdelApartments.getMaterials().favorites.length), 0);
    const archives = await page.evaluate(() => IdelSession.listArchives());
    assert.equal(archives.length, 1);
    assert.equal(archives[0].favoriteCount, 1);
    assert.equal(archives[0].screenshotCount, 0);
    const archive = await page.evaluate(id => IdelSession.getArchive(id), archives[0].id);
    assert.equal(archive.favorites[0].id, 1);
    assert.deepEqual(archive.screenshots, []);
    assert.equal(JSON.stringify(archive).includes('999'), false);
    await page.evaluate(id => IdelSession.deleteArchive(id), archives[0].id);
    assert.equal((await page.evaluate(() => IdelSession.listArchives())).length, 0);
    assert.deepEqual(errors, []);
    const isolated = await browser.newPage({ viewport: { width: 1, height: 1 } });
    isolated.on('pageerror', error => errors.push(error.message));
    await isolated.goto(pathToFileURL(path.join(__dirname, 'index.html')).href + '?data=standalone&mode=unreal&panel=saved', { waitUntil: 'domcontentloaded', timeout: 90000 });
    assert.equal(await isolated.locator('#app').evaluate(e => getComputedStyle(e).opacity), '0');
    await isolated.setViewportSize({ width: 1920, height: 1080 });
    await isolated.waitForFunction(() => !document.documentElement.hasAttribute('data-saved-preparing'));
    assert.equal(await isolated.locator('.saved-panel').evaluate(e => e.getBoundingClientRect().x), 503);
    await isolated.evaluate(() => { window.commands = []; window.addEventListener('idel-command', event => commands.push(event.detail)); });
    await isolated.evaluate(({ apartment, png }) => IdelWidget.setState({ view: 'saved', materials: { favorites: [apartment], screenshots: [{ id: 'capture-test', url: png, propertyId: 1, createdAt: new Date().toISOString() }] } }), { apartment, png });
    assert.equal(await isolated.locator('.saved-card').count(), 1);
    assert.equal(await isolated.locator('.saved-shot').count(), 1);
    assert.equal(await isolated.evaluate(() => IdelApartments.getMaterials().favorites.length), 1);
    await isolated.getByRole('button', { name: 'Подробнее' }).click();
    assert.equal(await isolated.evaluate(() => commands.at(-1)?.method), 'ui.saved.openApartment');
    await isolated.locator('.saved-shot-footer button').click();
    assert.equal(await isolated.evaluate(() => commands.at(-1)?.method), 'ui.saved.removeScreenshot');
    await isolated.getByRole('button', { name: 'Закрыть сохранённое' }).click();
    assert.equal(await isolated.evaluate(() => commands.at(-1)?.method), 'ui.panel.close');
    await isolated.evaluate(() => IdelWidget.setState({ view: 'saved', hidden: false }));
    await isolated.waitForFunction(() => !document.documentElement.hasAttribute('data-saved-preparing'));
    await isolated.getByRole('button', { name: 'Закрыть сохранённое' }).click();
    assert.equal(await isolated.evaluate(() => commands.at(-1)?.method), 'ui.panel.close');
    await isolated.close();
    const isolatedGallery = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
    await isolatedGallery.goto(pathToFileURL(path.join(__dirname, 'index.html')).href + '?data=standalone&mode=unreal&panel=gallery', { waitUntil: 'domcontentloaded', timeout: 90000 });
    assert.equal(await isolatedGallery.locator('.gallery-grid button').count(), 25);
    assert.equal(await isolatedGallery.locator('.top').count(), 0);
    await isolatedGallery.close();
    const galleryApi = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
    galleryApi.on('pageerror', error => errors.push(error.message));
    await galleryApi.addInitScript(() => { window.IdelConfig = { apiBaseUrl: 'https://api.example.test/api', galleryApi: true, galleryComplexId: 148 }; });
    let galleryRequests = 0;
    await galleryApi.route('https://api.example.test/api/presentation/gallery?*', route => {
      galleryRequests++;
      assert.equal(new URL(route.request().url()).searchParams.get('residentialComplex'), '148');
      return route.fulfill({ json: { items: [{ id: 2, title: 'Двор', image: 'https://media.example.test/courtyard.jpg', sort: 2 }, { id: 1, title: 'Фасад', image: 'https://media.example.test/facade.jpg', sort: 1 }] }, headers: { 'Access-Control-Allow-Origin': '*' } });
    });
    await galleryApi.goto(pathToFileURL(path.join(__dirname, 'index.html')).href + '?data=standalone&mode=unreal&panel=gallery', { waitUntil: 'domcontentloaded', timeout: 90000 });
    await galleryApi.locator('.gallery-grid button').first().waitFor();
    assert.equal(await galleryApi.locator('.gallery-grid button').count(), 2);
    assert.equal(await galleryApi.locator('.gallery-grid img').first().getAttribute('alt'), 'Фасад');
    assert.equal(galleryRequests, 1);
    await galleryApi.locator('.gallery-grid button').first().click();
    assert.equal(await galleryApi.getByRole('dialog', { name: 'Просмотр галереи' }).locator('.gallery-viewer-stage img').getAttribute('alt'), 'Фасад');
    await galleryApi.close();
    const toolbar = await browser.newPage({ viewport: { width: 340, height: 120 } });
    toolbar.on('pageerror', error => errors.push(error.message));
    let toolbarApiRequests = 0;
    toolbar.on('request', request => { if (request.url().includes('/api/')) toolbarApiRequests++; });
    await toolbar.goto(pathToFileURL(path.join(__dirname, 'index.html')).href + '?data=standalone&mode=unreal&panel=toolbar', { waitUntil: 'domcontentloaded', timeout: 90000 });
    await toolbar.evaluate(() => { window.commands = []; window.addEventListener('idel-command', event => commands.push(event.detail)); });
    await toolbar.locator('[data-action="ui.gallery"]').click();
    await toolbar.locator('[data-action="ui.favorites"]').click();
    await toolbar.locator('[data-action="ui.apartments"]').click();
    assert.deepEqual(await toolbar.evaluate(() => commands.slice(-3).map(item => item.method)), ['ui.gallery', 'ui.favorites', 'ui.apartments']);
    assert.equal(toolbarApiRequests, 0);
    await toolbar.locator('[data-action="scene.screenshot"]').click();
    const routedCapture = await toolbar.evaluate(() => commands.at(-1).params.captureId);
    assert.equal(await toolbar.evaluate(({ id, png }) => IdelApartments.setScreenshot({ captureId: id, url: png }), { id: routedCapture, png }), true);
    await toolbar.locator('.screenshot-flight').waitFor({ state: 'visible' });
    assert.equal(await toolbar.locator('[data-action="ui.favorites"] .screenshot-count').count(), 0);
    const screenshotDir = fs.mkdtempSync(path.join(os.tmpdir(), 'idel-screenshot-test-'));
    try {
      const screenshotFile = path.join(screenshotDir, 'captured.png');
      fs.copyFileSync(path.join(__dirname, 'assets/background.png'), screenshotFile);
      await toolbar.locator('[data-action="scene.screenshot"]').click();
      const fileCapture = await toolbar.evaluate(() => commands.at(-1).params.captureId);
      assert.equal(await toolbar.evaluate(({ captureId, url }) => IdelApartments.loadScreenshot({ captureId, url }), { captureId: fileCapture, url: pathToFileURL(screenshotFile).href }), true);
      assert.equal(await toolbar.evaluate(() => IdelApartments.getMaterials().screenshots.length), 2);
      await toolbar.locator('.screenshot-flight').waitFor({ state: 'visible' });
    } finally { fs.rmSync(screenshotDir, { recursive: true, force: true }); }
    assert.equal(await page.evaluate(id => IdelApartments.beginCapture({ captureId: id }), routedCapture), true);
    assert.equal(await page.evaluate(({ id, png }) => IdelApartments.setScreenshot({ captureId: id, url: png }), { id: routedCapture, png }), true);
    assert.equal(await page.evaluate(() => IdelApartments.getMaterials().screenshots.length), 1);
    await toolbar.close();
    assert.deepEqual(errors, []);
    console.log('PASS saved: privacy, favorite, screenshot history, local archive, isolated saved/gallery panels');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
